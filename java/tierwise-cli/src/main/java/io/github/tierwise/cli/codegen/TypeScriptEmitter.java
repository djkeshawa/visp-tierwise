package io.github.tierwise.cli.codegen;

import java.util.List;

/**
 * Writes the TypeScript module {@code tierwise.ts}: the key and feature name unions, the value and effect
 * maps, and a typed wrapper over the {@code @tierwise/evaluator} calls {@code resolve}, {@code resolveSync},
 * {@code decide} and {@code decideSync}.
 *
 * <p>The module imports only types from {@code @tierwise/evaluator}, so it adds no runtime code. It has
 * no identifiers that come from the declared names: names appear only as string literals.
 */
final class TypeScriptEmitter {

  /** The path of the generated module, relative to the output directory. */
  static final String FILE_NAME = "tierwise.ts";

  private TypeScriptEmitter() {
  }

  /**
   * Generates the module for a contract.
   *
   * @param contract the contract of the project
   * @return the one generated file
   */
  static List<GeneratedFile> emit(Contract contract) {
    return List.of(new GeneratedFile(FILE_NAME, module(contract)));
  }

  private static String module(Contract contract) {
    StringBuilder out = new StringBuilder();
    out.append("// Generated by tierwise codegen from bundle ").append(contract.bundleVersion()).append(".\n");
    out.append("// Do not edit: regenerate it with tierwise codegen.\n\n");
    out.append("import type { Context, Decision, Evaluator, FactSet, Resolved } from \"@tierwise/evaluator\";\n\n");

    out.append("/** The declared key names. */\n");
    out.append("export type KeyName =").append(aliasUnion(contract.keys().stream()
        .map(key -> Literals.quote(key.name())).toList())).append(";\n\n");

    out.append("/** The value type of each declared key. */\n");
    out.append("export interface KeyValues {\n");
    for (Contract.KeyDecl key : contract.keys()) {
      out.append("  ").append(Literals.quote(key.name())).append(": ").append(tsType(key.type())).append(";\n");
    }
    out.append("}\n\n");

    out.append("/** The keys whose result can be absent: the strategies min and max (MERGE-6). */\n");
    out.append("export type AbsentKeyName =").append(aliasUnion(contract.keys().stream()
        .filter(Contract.KeyDecl::absentPossible)
        .map(key -> Literals.quote(key.name())).toList())).append(";\n\n");

    out.append("/** The declared feature names. */\n");
    out.append("export type FeatureName =").append(aliasUnion(contract.features().stream()
        .map(feature -> Literals.quote(feature.name())).toList())).append(";\n\n");

    out.append("/** The effect type of each declared feature. */\n");
    out.append("export interface FeatureEffects {\n");
    for (Contract.FeatureDecl feature : contract.features()) {
      out.append("  ").append(Literals.quote(feature.name())).append(": ").append(tsEffect(feature.returns()))
          .append(";\n");
    }
    out.append("}\n\n");

    out.append("""
        /** A resolved key, typed by its name. */
        export interface TypedResolved<K extends KeyName> {
          readonly key: K;
          /** The value; null is possible only for a key in AbsentKeyName. */
          readonly value: K extends AbsentKeyName ? KeyValues[K] | null : KeyValues[K];
          readonly raw: Resolved;
        }

        /** A decision, typed by its feature. */
        export interface TypedDecision<F extends FeatureName> {
          readonly feature: F;
          readonly effect: FeatureEffects[F];
          readonly raw: Decision;
        }

        /**
         * Typed calls over an evaluator. The wrapper only converts types: every call goes to the evaluator,
         * and no call reads one scope's raw value. Browser evaluation is for display only.
         */
        export class TypedEvaluator {
          private readonly evaluator: Evaluator;

          constructor(evaluator: Evaluator) {
            this.evaluator = evaluator;
          }

          /** The bundle version of the evaluator. */
          get bundleVersion(): string {
            return this.evaluator.bundleVersion;
          }

          /** Resolves a key; calls the providers that the context needs. */
          async resolve<K extends KeyName>(context: Context | undefined, key: K): Promise<TypedResolved<K>> {
            return typedResolved(key, await this.evaluator.resolve(context, key));
          }

          /** Resolves a key without a provider call. */
          resolveSync<K extends KeyName>(context: Context | undefined, key: K): TypedResolved<K> {
            return typedResolved(key, this.evaluator.resolveSync(context, key));
          }

          /** Decides a feature for one entity. It calls no provider. */
          async decide<F extends FeatureName>(
            context: Context | undefined,
            feature: F,
            facts?: FactSet,
          ): Promise<TypedDecision<F>> {
            return typedDecision(feature, await this.evaluator.decide(context, feature, facts));
          }

          /** Decides a feature, returning the result directly. */
          decideSync<F extends FeatureName>(
            context: Context | undefined,
            feature: F,
            facts?: FactSet,
          ): TypedDecision<F> {
            return typedDecision(feature, this.evaluator.decideSync(context, feature, facts));
          }
        }

        function typedResolved<K extends KeyName>(key: K, raw: Resolved): TypedResolved<K> {
          return { key, value: raw.value as unknown as TypedResolved<K>["value"], raw };
        }

        function typedDecision<F extends FeatureName>(feature: F, raw: Decision): TypedDecision<F> {
          return { feature, effect: raw.effect as unknown as FeatureEffects[F], raw };
        }
        """);
    return out.toString();
  }

  /**
   * Returns the TypeScript type of a declared value.
   *
   * @param type the declared type
   * @return the type expression
   */
  static String tsType(TypeDecl type) {
    if (type instanceof TypeDecl.BooleanType) {
      return "boolean";
    }
    if (type instanceof TypeDecl.IntegerType) {
      return "number";
    }
    if (type instanceof TypeDecl.DecimalType || type instanceof TypeDecl.StringType) {
      return "string";
    }
    if (type instanceof TypeDecl.EnumType enumType) {
      return inlineUnion(enumType.values().stream().map(Literals::quote).toList());
    }
    if (type instanceof TypeDecl.SetType set) {
      return "ReadonlyArray<" + inlineUnion(set.universe().stream().map(Literals::quote).toList()) + ">";
    }
    if (type instanceof TypeDecl.ListType list) {
      return "ReadonlyArray<" + tsType(list.items()) + ">";
    }
    TypeDecl.ObjectType object = (TypeDecl.ObjectType) type;
    StringBuilder fields = new StringBuilder("{");
    for (var entry : object.fields().entrySet()) {
      fields.append(' ').append("readonly ").append(Literals.quote(entry.getKey()))
          .append(entry.getValue().optional() ? "?" : "").append(": ")
          .append(tsType(entry.getValue().type())).append(';');
    }
    return fields.append(" }").toString();
  }

  private static String tsEffect(Contract.Returns returns) {
    if (returns instanceof Contract.Returns.EnumForm form) {
      String union = inlineUnion(form.effects().stream().map(Literals::quote).toList());
      return form.nullable() ? union + " | null" : union;
    }
    return tsType(new TypeDecl.ObjectType(((Contract.Returns.ObjectForm) returns).fields()));
  }

  /**
   * Joins quoted literals into one line: {@code "a" | "b"}, or {@code never} for an empty list.
   *
   * @param literals the literals, already quoted
   * @return the union type
   */
  private static String inlineUnion(List<String> literals) {
    return literals.isEmpty() ? "never" : String.join(" | ", literals);
  }

  /**
   * Writes the right-hand side of a type alias: one literal on the line of the {@code =}, or one member
   * for each line below it when there are several.
   *
   * @param literals the literals, already quoted
   * @return the text that follows the {@code =}, without the semicolon
   */
  private static String aliasUnion(List<String> literals) {
    if (literals.isEmpty()) {
      return " never";
    }
    if (literals.size() == 1) {
      return " " + literals.get(0);
    }
    StringBuilder union = new StringBuilder();
    for (String literal : literals) {
      union.append("\n  | ").append(literal);
    }
    return union.toString();
  }
}
