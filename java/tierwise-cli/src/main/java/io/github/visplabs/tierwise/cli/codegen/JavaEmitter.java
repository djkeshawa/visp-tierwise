package io.github.visplabs.tierwise.cli.codegen;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Writes the Java package: the handle interfaces {@code Key} and {@code Feature}, the constant classes
 * {@code Keys} and {@code Features} (with one enum for each feature that returns an enum), and the typed
 * facade {@code TypedEvaluator} with its result records.
 *
 * <p>The generated code depends only on the public classes of {@code io.github.visplabs.tierwise.core}. Every
 * unchecked cast is safe because the bundle fixes the Java type of each value, as {@code Plain} gives
 * it: {@code Boolean}, {@code Long}, {@code String}, {@code List<Object>} and {@code Map<String, Object>}.
 */
final class JavaEmitter {

  private final Contract contract;
  private final String javaPackage;
  private final String banner;

  private JavaEmitter(Contract contract, String javaPackage) {
    this.contract = contract;
    this.javaPackage = javaPackage;
    this.banner = "// Generated by tierwise codegen from bundle " + contract.bundleVersion() + ".\n"
        + "// Do not edit: regenerate it with tierwise codegen.\n";
  }

  /**
   * Generates the package for a contract.
   *
   * @param contract the contract of the project
   * @param javaPackage the package name, dot-separated
   * @return the files, in a fixed order
   * @throws IllegalArgumentException if the package name is not a Java package name
   * @throws CodegenException if two declared names would map to one Java identifier
   */
  static List<GeneratedFile> emit(Contract contract, String javaPackage) {
    Identifiers.checkPackage(javaPackage);
    JavaEmitter emitter = new JavaEmitter(contract, javaPackage);
    return List.of(
        emitter.file("Key.java", emitter.keyInterface()),
        emitter.file("Feature.java", emitter.featureInterface()),
        emitter.file("Keys.java", emitter.keysClass()),
        emitter.file("Features.java", emitter.featuresClass()),
        emitter.file("TypedEvaluator.java", emitter.typedEvaluator()),
        emitter.file("TypedResolved.java", emitter.typedResolved()),
        emitter.file("TypedDecision.java", emitter.typedDecision()));
  }

  /**
   * Returns the Java type of a declared value. A set has the members of its universe, which are strings
   * (TYPE-40, TYPE-41).
   *
   * @param type the declared type
   * @return the Java type, with boxed primitives
   */
  static String javaType(TypeDecl type) {
    if (type instanceof TypeDecl.BooleanType) {
      return "Boolean";
    }
    if (type instanceof TypeDecl.IntegerType) {
      return "Long";
    }
    if (type instanceof TypeDecl.DecimalType || type instanceof TypeDecl.StringType
        || type instanceof TypeDecl.EnumType) {
      return "String";
    }
    if (type instanceof TypeDecl.SetType) {
      return "List<String>";
    }
    if (type instanceof TypeDecl.ListType list) {
      return "List<" + javaType(list.items()) + ">";
    }
    return "Map<String, Object>";
  }

  private GeneratedFile file(String name, String body) {
    return new GeneratedFile(
        javaPackage.replace('.', '/') + "/" + name,
        banner + "package " + javaPackage + ";\n\n" + body);
  }

  private String keyInterface() {
    return """
        /**
         * A typed handle for one declared key. The type parameter is the Java type of the key's value.
         *
         * @param <T> the Java type of the value
         */
        public interface Key<T> {

          /**
           * Returns the declared name of the key, as the evaluator takes it.
           *
           * @return the name
           */
          String name();
        }
        """;
  }

  private String featureInterface() {
    return """
        /**
         * A typed handle for one declared feature. The type parameter is the Java type of its effect.
         *
         * @param <R> the Java type of the effect
         */
        public interface Feature<R> {

          /**
           * Returns the declared name of the feature, as the evaluator takes it.
           *
           * @return the name
           */
          String name();

          /**
           * Converts the effect of a decision to the Java type of the feature.
           *
           * @param effect the effect as the evaluator returns it: a string, a map, or {@code null} for a
           *     nullable enum
           * @return the typed effect
           */
          R decode(Object effect);
        }
        """;
  }

  private String keysClass() {
    Map<String, String> owners = new HashMap<>();
    List<String> constants = new ArrayList<>();
    boolean usesList = false;
    boolean usesMap = false;
    for (Contract.KeyDecl key : contract.keys()) {
      String constant = Identifiers.constantName(key.name());
      Identifiers.claim(owners, constant, key.name(), "key");
      String type = javaType(key.type());
      usesList |= type.contains("List<");
      usesMap |= type.contains("Map<");
      constants.add("  public static final Key<" + type + "> " + constant + " =\n      new Ref<>("
          + Literals.quote(key.name()) + ");\n");
    }
    StringBuilder out = new StringBuilder();
    if (usesList) {
      out.append("import java.util.List;\n");
    }
    if (usesMap) {
      out.append("import java.util.Map;\n");
    }
    if (usesList || usesMap) {
      out.append('\n');
    }
    out.append("""
        /**
         * The typed key handles of the project: one constant for each declared key. Pass a constant to
         * {@link TypedEvaluator#resolve}.
         */
        public final class Keys {

          private Keys() {
          }
        """);
    for (String constant : constants) {
      out.append('\n').append(constant);
    }
    out.append("""

          private record Ref<T>(String name) implements Key<T> {
          }
        }
        """);
    return out.toString();
  }

  private String featuresClass() {
    Map<String, String> constantOwners = new HashMap<>();
    Map<String, String> enumOwners = new HashMap<>();
    List<String> constants = new ArrayList<>();
    List<String> enums = new ArrayList<>();
    for (Contract.FeatureDecl feature : contract.features()) {
      String constant = Identifiers.constantName(feature.name());
      Identifiers.claim(constantOwners, constant, feature.name(), "feature");
      if (feature.returns() instanceof Contract.Returns.EnumForm form) {
        String enumName = Identifiers.enumTypeName(feature.name());
        Identifiers.claim(enumOwners, enumName, feature.name(), "feature effect type");
        enums.add(enumSource(enumName, form.effects()));
        constants.add("  public static final Feature<" + enumName + "> " + constant + " =\n      new Ref<>("
            + Literals.quote(feature.name()) + ", " + enumName + "::fromWire);\n");
      } else {
        constants.add("  public static final Feature<Map<String, Object>> " + constant + " =\n      new Ref<>("
            + Literals.quote(feature.name()) + ", Features::asObject);\n");
      }
    }
    StringBuilder out = new StringBuilder("import java.util.Map;\nimport java.util.function.Function;\n\n");
    out.append("""
        /**
         * The typed feature handles of the project: one constant for each declared feature, and one enum
         * of the effects for each feature that returns an enum. Pass a constant to
         * {@link TypedEvaluator#decide}.
         */
        public final class Features {

          private Features() {
          }
        """);
    for (String constant : constants) {
      out.append('\n').append(constant);
    }
    for (String enumType : enums) {
      out.append('\n').append(enumType);
    }
    out.append("""

          @SuppressWarnings("unchecked")
          private static Map<String, Object> asObject(Object raw) {
            return (Map<String, Object>) raw;
          }

          private record Ref<R>(String name, Function<Object, R> decoder) implements Feature<R> {
            @Override
            public R decode(Object effect) {
              return decoder.apply(effect);
            }
          }
        }
        """);
    return out.toString();
  }

  private static String enumSource(String enumName, List<String> effects) {
    Map<String, String> owners = new HashMap<>();
    StringBuilder constants = new StringBuilder();
    for (int i = 0; i < effects.size(); i++) {
      String effect = effects.get(i);
      String constant = Identifiers.constantName(effect);
      Identifiers.claim(owners, constant, effect, "effect");
      constants.append("    ").append(constant).append('(').append(Literals.quote(effect)).append(')')
          .append(i + 1 < effects.size() ? ",\n" : ";\n");
    }
    return """
          /** The effects of one feature, as the bundle declares them. */
          public enum %1$s {
        %2$s
            private final String wire;

            %1$s(String wire) {
              this.wire = wire;
            }

            /**
             * Returns the effect as the evaluator spells it.
             *
             * @return the declared spelling
             */
            public String wire() {
              return wire;
            }

            static %1$s fromWire(Object raw) {
              if (raw == null) {
                return null;
              }
              for (%1$s effect : values()) {
                if (effect.wire.equals(raw)) {
                  return effect;
                }
              }
              throw new IllegalArgumentException("not a declared effect: " + raw);
            }
          }
        """.formatted(enumName, constants);
  }

  private String typedEvaluator() {
    return """
        import io.github.visplabs.tierwise.core.Context;
        import io.github.visplabs.tierwise.core.Decision;
        import io.github.visplabs.tierwise.core.Evaluator;
        import io.github.visplabs.tierwise.core.FactSet;
        import io.github.visplabs.tierwise.core.Resolved;
        import java.util.Objects;

        /**
         * Typed calls over an {@link Evaluator}. A key or feature handle fixes the Java type of the result, so
         * a caller gets the value type that the project declares. The facade only converts types: every call
         * goes to the evaluator, and no call reads one scope's raw value.
         */
        public final class TypedEvaluator {

          private final Evaluator evaluator;

          /**
           * Creates the facade.
           *
           * @param evaluator the evaluator to call
           */
          public TypedEvaluator(Evaluator evaluator) {
            this.evaluator = Objects.requireNonNull(evaluator, "evaluator");
          }

          /**
           * Resolves a key, calling providers where the context needs them.
           *
           * @param context the context, or {@code null} for the empty context
           * @param key the key handle
           * @param <T> the value type of the key
           * @return the typed result
           */
          public <T> TypedResolved<T> resolve(Context context, Key<T> key) {
            return typed(key, evaluator.resolve(context, key.name()));
          }

          /**
           * Resolves a key without calling a provider.
           *
           * @param context the context, or {@code null} for the empty context
           * @param key the key handle
           * @param <T> the value type of the key
           * @return the typed result
           */
          public <T> TypedResolved<T> resolveLocal(Context context, Key<T> key) {
            return typed(key, evaluator.resolveLocal(context, key.name()));
          }

          /**
           * Decides a feature for one entity. It calls no provider.
           *
           * @param context the context, or {@code null} for the empty context
           * @param feature the feature handle
           * @param facts the facts of the decided entity and its children, or {@code null} for none
           * @param <R> the Java type of the effect
           * @return the typed decision
           */
          public <R> TypedDecision<R> decide(Context context, Feature<R> feature, FactSet facts) {
            Decision raw = evaluator.decide(context, feature.name(), facts);
            return new TypedDecision<>(feature.name(), feature.decode(raw.effect()), raw);
          }

          @SuppressWarnings("unchecked")
          private static <T> TypedResolved<T> typed(Key<T> key, Resolved raw) {
            return new TypedResolved<>(key.name(), (T) raw.value(), raw);
          }
        }
        """;
  }

  private String typedResolved() {
    return """
        import io.github.visplabs.tierwise.core.Resolved;

        /**
         * The result of resolving a key, typed by the key.
         *
         * @param key the declared key name
         * @param value the value; {@code null} only when the result is absent, which can happen only for a key
         *     whose strategy is {@code min} or {@code max}
         * @param provenance the untyped result of the evaluator, with its provenance
         * @param <T> the value type of the key
         */
        public record TypedResolved<T>(String key, T value, Resolved provenance) {

          /**
           * Tells whether the result has a value.
           *
           * @return {@code true} unless the result is absent
           */
          public boolean hasValue() {
            return value != null;
          }
        }
        """;
  }

  private String typedDecision() {
    return """
        import io.github.visplabs.tierwise.core.Decision;

        /**
         * The result of deciding a feature, typed by the feature.
         *
         * @param feature the declared feature name
         * @param effect the effect; {@code null} only for a nullable enum
         * @param provenance the untyped decision of the evaluator, with its provenance
         * @param <R> the Java type of the effect
         */
        public record TypedDecision<R>(String feature, R effect, Decision provenance) {
        }
        """;
  }
}
