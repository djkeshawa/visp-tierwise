// The self-contained SHA-256 against node:crypto (ADR 0012 section 3). node:crypto is used in this test only.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { test } from 'node:test';
import fc from 'fast-check';
import { sha } from './support.mjs';

const reference = (bytes) => createHash('sha256').update(bytes).digest('hex');

test('known digests (FIPS 180-4 examples)', () => {
  const encoder = new TextEncoder();
  assert.equal(sha.sha256Hex(new Uint8Array(0)), 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855');
  assert.equal(sha.sha256Hex(encoder.encode('abc')), 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
  assert.equal(
    sha.sha256Hex(encoder.encode('abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq')),
    '248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1',
  );
});

test('every length from 0 to 300 bytes, including the padding boundaries', () => {
  for (let length = 0; length <= 300; length++) {
    const bytes = Uint8Array.from({ length }, (_, index) => (index * 31 + length) & 0xff);
    assert.equal(sha.sha256Hex(bytes), reference(bytes), `length ${length}`);
  }
});

test('one million bytes of "a"', () => {
  const bytes = new Uint8Array(1_000_000).fill(0x61);
  assert.equal(sha.sha256Hex(bytes), 'cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0');
});

test('differential: generated byte arrays', () => {
  fc.assert(
    fc.property(fc.uint8Array({ maxLength: 600 }), (bytes) => {
      assert.equal(sha.sha256Hex(bytes), reference(bytes));
    }),
    { numRuns: 1000 },
  );
});

test('differential: generated byte arrays that are views into a larger buffer', () => {
  fc.assert(
    fc.property(fc.uint8Array({ minLength: 8, maxLength: 200 }), fc.nat(7), (bytes, start) => {
      const view = bytes.subarray(start);
      assert.equal(sha.sha256Hex(view), reference(view));
    }),
    { numRuns: 300 },
  );
});

test('differential: generated text, encoded as UTF-8', () => {
  fc.assert(
    fc.property(fc.string({ unit: 'binary', maxLength: 200 }), (text) => {
      const bytes = new TextEncoder().encode(text);
      assert.equal(sha.sha256Hex(bytes), reference(bytes));
    }),
    { numRuns: 500 },
  );
});

test('the digest does not change its input', () => {
  const bytes = Uint8Array.from({ length: 130 }, (_, index) => index);
  const copy = bytes.slice();
  sha.sha256(bytes);
  assert.deepEqual(bytes, copy);
});
